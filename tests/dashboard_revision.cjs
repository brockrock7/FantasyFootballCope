const assert=require('node:assert/strict');
const path=require('node:path');
module.exports=async function(page){
  await page.locator('[data-tab="live"]').click();
  const weeks=await page.locator('#liveWeeks button').allTextContents();
  assert.deepEqual(weeks,[...weeks].sort((a,b)=>Number(a.slice(1))-Number(b.slice(1))));
  await page.locator('#liveWeeks button').first().click();
  assert(await page.locator('#projectionCard').isHidden());
  assert.deepEqual(await page.locator('.matchup-mirror thead tr').last().locator('th').allTextContents(),['Starter','Proj.','Actual','Actual','Proj.','Starter']);
  for(const width of [320,390,430]){
    await page.setViewportSize({width,height:844});
    const fits=await page.locator('.matchup-mirror-scroll').evaluate(node=>node.scrollWidth<=node.clientWidth+1);
    assert(fits,'starter projections fit without horizontal scrolling at '+width);
  }
  await page.setViewportSize({width:1440,height:1000});
  assert(await page.locator('.matchup-mirror').evaluate(node=>node.clientWidth>800));
  await page.locator('#liveWeeks button').last().click();
  assert(await page.locator('#projectionCard').isVisible());
  await page.locator('[data-tab="team"]').click();await page.locator('[data-team-view="position"]').click();
  assert(await page.locator('#team-view-position>.card').first().locator('#radars').count());
  await page.locator('#positionTeams button').nth(2).click();
  assert.equal(await page.evaluate(()=>posChart.options.scales.x.min),await page.evaluate(()=>Math.min(0,D.position_negative_min?.[document.querySelector('#positionTeams button.active').title]||0,...posChart.data.labels.map((_,i)=>posChart.data.datasets.reduce((sum,ds)=>sum+Math.min(0,ds.data[i]||0),0)))));
  await page.locator('[data-team-view="acquisition"]').click();
  assert.equal(await page.evaluate(()=>sourceChart.options.scales.x.min),0);
  assert.equal(await page.evaluate(()=>Chart.getChart('sourceTotalsChart').options.scales.x.min),0);
  await page.locator('[data-team-view="roster"]').click();assert(await page.locator('#rosterStatsTable .mean-delta').count());
  await page.locator('[data-tab="trades"]').click();await page.locator('[data-trades-view="suggestions"]').click();
  assert.equal(await page.evaluate(()=>suggestedTrades.getMode()),'decoy');
  assert.equal(await page.locator('.suggestions-gate').count(),0);
  const started=Date.now();await page.locator('[data-trades-view="suggestions"]').dblclick();
  assert.equal(await page.evaluate(()=>suggestedTrades.getMode()),'real');
  await page.waitForFunction(()=>!document.querySelector('.suggestions-status').textContent.startsWith('Evaluating'),{},{timeout:180000});
  console.log('Suggestions elapsed ms:',Date.now()-started);
  const realCount=await page.locator('.suggestions-table tbody tr').count();
  const packageSizes=await page.locator('.suggestions-table tbody tr').evaluateAll(rows=>rows.map(row=>[row.cells[0].querySelectorAll('.suggestion-player').length,row.cells[1].querySelectorAll('.suggestion-player').length]));
  assert(packageSizes.some(sizes=>sizes.some(size=>size>1)),'multi-player suggestions are displayed');
  assert(packageSizes.every(sizes=>sizes.every(size=>size>=1&&size<=4)),'packages stay within four per side');
  assert(await page.evaluate(()=>{
    const data=D.trade_calculator,own=suggestedTrades.getState().team;
    return [...document.querySelectorAll('.suggestions-table tbody tr')].slice(0,8).every(row=>{
      const partner=Object.keys(data.teams).find(id=>(D.team_abbrevs[data.teams[id].name]||data.teams[id].name)===row.cells[2].textContent);
      const ids=(cell,team)=>[...cell.querySelectorAll('.suggestion-player')].map(node=>String(data.teams[team].players.find(p=>p.name===node.firstChild.textContent).id));
      const state={teamA:own,teamB:partner,sendA:ids(row.cells[0],own),sendB:ids(row.cells[1],partner),startWeek:data.weeks[0],endWeek:data.weeks.at(-1)};
      const full=TradeCalculator.evaluateTrade(data,state);
      return [['sendA','b'],['sendB','a']].every(([field,receiver])=>state[field].every(id=>full[receiver].after-TradeCalculator.evaluateTrade(data,{...state,[field]:state[field].filter(value=>value!==id)})[receiver].after>1e-6));
    });
  }),'each displayed player improves their receiving roster compared with the same trade without that player');
  await page.locator('.suggestions-table [data-sort="b"]').click();
  assert.equal(await page.evaluate(()=>suggestedTrades.getState().sort),'b');
  await page.setViewportSize({width:390,height:844});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  if(process.env.DASHBOARD_SCREENSHOT_DIR)await page.screenshot({path:path.join(process.env.DASHBOARD_SCREENSHOT_DIR,'suggested-trades-mobile.png'),fullPage:true});
  await page.locator('[data-trades-view="history"]').click();await page.locator('[data-trades-view="suggestions"]').click();
  assert.equal(await page.evaluate(()=>suggestedTrades.getMode()),'decoy');
  await page.waitForFunction(()=>!document.querySelector('.suggestions-status').textContent.startsWith('Evaluating'));
  await page.locator('.suggestions-content [data-kind="partners"]:not([data-value="all"])').nth(0).click();
  await page.locator('.suggestions-content [data-kind="partners"]:not([data-value="all"])').nth(1).click();
  await page.locator('.suggestions-content [data-kind="positions"]:not([data-value="all"])').nth(0).click();
  await page.locator('.suggestions-content [data-kind="positions"]:not([data-value="all"])').nth(1).click();
  assert.equal(await page.evaluate(()=>suggestedTrades.getState().partners.length),2);
  assert.equal(await page.evaluate(()=>suggestedTrades.getState().positions.length),2);
  assert(await page.evaluate(()=>[...document.querySelectorAll('.suggestions-table tbody .suggestion-player small')].every(node=>suggestedTrades.getState().positions.includes(node.textContent))),'every sent and received player belongs to an allowed position');
  const decoyCount=await page.locator('.suggestions-table tbody tr').count();
  assert(await page.locator('.suggestions-table tbody td:nth-child(4)').evaluateAll(cells=>cells.every(cell=>Number(cell.textContent)>0)));
  console.log('PASS: ascending weeks, mobile/desktop matchup fit, actual-score center, historical card visibility, radar order, team-specific domain, mean delta, suggested trade click modes, multi-select filters and sort. Counts:',realCount,decoyCount);
};
