const assert=require('node:assert/strict');
const {searchPackages,hasOnlyContributors}=require('../suggested_trades.js');
const {evaluateTrade}=require('../trade_calculator.js');
const player=(id,position,points,extra={})=>({id,name:id,position,projections:{1:{points},2:{points}},...extra});
const fixture=()=>({weeks:[1,2],lineup_slots:['RB','WR'],teams:{a:{players:[player('ar1','RB',30),player('ar2','RB',25),player('aw','WR',8)]},b:{players:[player('bw1','WR',30),player('bw2','WR',25),player('br','RB',8)]}}});
const state={teamA:'a',teamB:'b',sendA:['ar2'],sendB:['bw2'],startWeek:1,endWeek:2};
let d=fixture();
assert(hasOnlyContributors(d,evaluateTrade(d,state)),'both incoming players improve their receiving lineup');
d.teams.a.players.push(player('filler','QB',20));
assert(!hasOnlyContributors(d,evaluateTrade(d,{...state,sendA:['ar2','filler']})),'a positive projection with no lineup role is excluded on the sent side');
d=fixture();d.teams.a.players.push(player('equal','WR',25));
assert(!hasOnlyContributors(d,evaluateTrade(d,state)),'a tied starter adds no marginal points on the received side');
d.teams.a.players.find(p=>p.id==='equal').bye_week=2;
assert(hasOnlyContributors(d,evaluateTrade(d,state)),'a player who improves only bye coverage is retained');
d=fixture();d.teams.b.players.push(player('same','WR',25));
assert(!hasOnlyContributors(d,evaluateTrade(d,{...state,sendB:['bw2','same']})),'duplicate incoming options cannot pad a package');
d={weeks:[1,2],lineup_slots:['RB','WR'],teams:{a:{players:[player('ar2','RB',25)]},b:{players:[player('bw2','WR',25)]}},free_agents:[player('far','RB',25),player('faw','WR',25)]};
assert(!hasOnlyContributors(d,evaluateTrade(d,state)),'filling a vacancy without beating its waiver replacement adds no value');
d.free_agents.forEach(p=>Object.values(p.projections).forEach(row=>row.points=20));
assert(hasOnlyContributors(d,evaluateTrade(d,state)),'upgrading a replacement does add value');
console.log('PASS: filler, tied starters, duplicate options, bye coverage, and waiver replacement contribution checks');
(async()=>{
 const own=Array.from({length:5},(_,i)=>({id:i,name:'A'+i,projections:{1:{points:10+i}}}));
 const other=own.map(p=>({...p,id:p.id+10}));
 const results=await searchPackages(own,other,row=>({a:row.send.length+row.receive.length,b:row.send.length-row.receive.length}));
 const sizes=new Set(),keys=new Set();
 for(const row of results){
   assert(row.send.length>=1&&row.send.length<=4&&row.receive.length>=1&&row.receive.length<=4);
   assert.equal(new Set(row.send.map(p=>p.id)).size,row.send.length);
   assert.equal(new Set(row.receive.map(p=>p.id)).size,row.receive.length);
   sizes.add(row.send.length+':'+row.receive.length);
   const key=row.send.map(p=>p.id).sort().join(',')+'|'+row.receive.map(p=>p.id).sort().join(',');assert(!keys.has(key));keys.add(key);
 }
 assert.equal(sizes.size,16,'every 1–4 package-size pairing is evaluated');
 assert.equal(results.filter(r=>r.send.length===1&&r.receive.length===1).length,25,'all singles evaluated');
 assert.deepEqual(await searchPackages(own,other,()=>{throw Error('cancelled search should not evaluate');},{cancelled:()=>true}),[]);
 const useful=await searchPackages(own,other,row=>({a:1,b:1,contributes:row.send.length>1&&row.receive.length>1}));
 assert(useful.length>0&&useful.every(row=>row.send.length>1&&row.receive.length>1),'rejected packages seed larger searches without being displayed');
 console.log('PASS: all 16 package-size pairs, exhaustive singles, distinct players, deduplicated trades and cancellation; candidates:',results.length);
})().catch(error=>{console.error(error);process.exitCode=1;});
